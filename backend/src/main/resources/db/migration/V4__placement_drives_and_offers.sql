-- 2. Opportunity / Internship Backlog Criteria
ALTER TABLE internships ADD COLUMN IF NOT EXISTS max_backlogs INT DEFAULT 0;

-- 3. Placement Drives Table
CREATE TABLE IF NOT EXISTS placement_drives (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    academic_year VARCHAR(50) NOT NULL,
    company_id BIGINT REFERENCES companies(id) ON DELETE CASCADE,
    internship_id BIGINT REFERENCES internships(id) ON DELETE SET NULL,
    drive_date TIMESTAMP NOT NULL,
    registration_deadline TIMESTAMP NOT NULL,
    venue_or_link VARCHAR(255),
    status VARCHAR(50) NOT NULL DEFAULT 'UPCOMING',
    eligible_branches VARCHAR(255),
    min_cgpa DECIMAL(4,2) DEFAULT 0.00,
    rules_summary TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_placement_drives_status ON placement_drives(status);
CREATE INDEX IF NOT EXISTS idx_placement_drives_date ON placement_drives(drive_date);

-- 4. Formal Offers & Joining Table
CREATE TABLE IF NOT EXISTS offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    company_id BIGINT NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
    internship_id BIGINT NOT NULL REFERENCES internships(id) ON DELETE CASCADE,
    designation VARCHAR(150) NOT NULL,
    ctc_or_stipend DECIMAL(12,2) NOT NULL,
    offer_letter_url VARCHAR(500),
    offer_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    joining_date TIMESTAMP,
    status VARCHAR(50) NOT NULL DEFAULT 'OFFERED',
    response_notes TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_offers_student ON offers(student_id);
CREATE INDEX IF NOT EXISTS idx_offers_company ON offers(company_id);
CREATE INDEX IF NOT EXISTS idx_offers_status ON offers(status);

